#if DEBUG
import Foundation
import AppKit
import BetterWorkspaceCore

/// Developer acceptance check: creates only explicitly named validation fixtures,
/// uses the production coordinator, and archives only IDs created in this run.
enum NotionGraphLiveValidation {
    static func run(client: NotionClient, configured: [ProjectGraphSource]) async throws {
        let stamp = UUID().uuidString
        let prefix = "Better Workspace sync validation " + stamp
        let directory = try FileManager.default.url(for: .cachesDirectory, in: .userDomainMask, appropriateFor: nil, create: true).appendingPathComponent("BetterWorkspace/SyncValidation/" + stamp)
        try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
        let store = try ProjectGraphStore(database: Database(url: directory.appendingPathComponent("validation.sqlite")))
        let sources = try await configured.asyncMap { try await client.graphSource($0.id, kind: $0.kind) }
        guard Set(sources.map(\.kind)) == Set(ProjectEntityKind.allCases) else { throw NotionProjectSync.SyncError.unsupported("All 12 sources must be resolved before live round-trip validation.") }
        try store.write("sources", sources)
        var records = sources.map { source -> ProjectGraphRecord in
            var record = ProjectGraphRecord(sourceID: source.id, kind: source.kind)
            for (name, schema) in source.schema.object where schema["type"].string == "title" { record.set(name, value: ProjectServiceBridge.text(prefix + " · " + source.kind.title), source: source) }
            return record
        }
        func reference(_ kind: ProjectEntityKind) -> String { records.first { $0.kind == kind }!.id }
        for index in records.indices {
            let source = sources.first { $0.id == records[index].sourceID }!
            if records[index].kind != .projects {
                for (name, schema) in source.schema.object where schema["type"].string == "relation" && ["project", "projects"].contains(name.lowercased()) && schema["relation"]["data_source_id"].string == sources.first(where: { $0.kind == .projects })?.id {
                    records[index].set(name, value: ProjectJSON([["id": reference(.projects)]]), source: source)
                }
            }
            switch records[index].kind {
            case .projects:
                records[index].set("one liner", value: ProjectServiceBridge.text("Initial round-trip value"), source: source)
                records[index].set("thumbnail", value: ProjectJSON([["id": reference(.assets)]]), source: source)
            case .tasks:
                records[index].set("Features", value: ProjectJSON([["id": reference(.features)]]), source: source)
                records[index].set("milestones", value: ProjectJSON([["id": reference(.milestones)]]), source: source)
            case .assets:
                records[index].set("collections", value: ProjectJSON([["id": reference(.collections)]]), source: source)
                records[index].set("relative path", value: ProjectServiceBridge.text("Missing validation preview.png"), source: source)
                records[index].set("storage", value: ProjectJSON(["name": "Workspace"]), source: source)
                guard let preview = source.property(named: "preview") else { throw NotionProjectSync.SyncError.unsupported("Assets preview property is unavailable.") }
                // A tiny PNG generated by this test; no personal file is uploaded.
                let png = directory.appendingPathComponent("validation.png")
                let bitmap = NSBitmapImageRep(bitmapDataPlanes: nil, pixelsWide: 16, pixelsHigh: 16, bitsPerSample: 8, samplesPerPixel: 4, hasAlpha: true, isPlanar: false, colorSpaceName: .deviceRGB, bytesPerRow: 0, bitsPerPixel: 0)!
                bitmap.bitmapData!.initialize(repeating: 180, count: bitmap.bytesPerRow * bitmap.pixelsHigh)
                let data = bitmap.representation(using: .png, properties: [:])!
                try data.write(to: png)
                let attributes = try FileManager.default.attributesOfItem(atPath: png.path)
                records[index].pendingUploads = [.init(propertyID: preview.id, url: png, contentType: "image/png", byteCount: data.count, modifiedAt: attributes[.modificationDate] as? Date)]
            case .resources:
                records[index].set("url", value: .string("https://example.com/better-workspace-validation"), source: source)
                records[index].set("collections", value: ProjectJSON([["id": reference(.collections)]]), source: source)
                records[index].set("versions", value: ProjectJSON([["id": reference(.versions)]]), source: source)
            case .milestones: records[index].set("due date (manual)", value: ProjectJSON(["start": "2026-10-10"]), source: source)
            default: break
            }
            try store.save(records[index])
        }
        let coordinator = NotionProjectSync(store: store, client: client)
        let ids = Set(records.map(\.id))
        var validationError: Error?
        do {
            try await coordinator.push(ids: ids, reviewed: records)
            records = try store.records()
            guard records.allSatisfy({ $0.pageID != nil && !$0.changes.contains(where: { $0.state == .outgoing || $0.state == .conflict }) }) else { throw NotionProjectSync.SyncError.unsupported("Creation did not acknowledge all requested fields.") }
            for var record in records {
                let source = sources.first { $0.id == record.sourceID }!
                if record.kind == .projects { record.set("one liner", value: ProjectServiceBridge.text("Updated round-trip value"), source: source); record.set("hero", value: ProjectJSON([["id": records.first { $0.kind == .assets }!.pageID!]]), source: source) }
                if record.kind == .resources { record.set("url", value: .string("https://example.com/better-workspace-validation-updated"), source: source) }
                if record.kind == .milestones { record.set("due date (manual)", value: .null, source: source) }
                try store.save(record)
            }
            // Review canonical, freshly fetched values before the update round trip.
            try await refresh(store: store, sources: sources, client: client)
            let updated = try store.records()
            try await coordinator.push(ids: ids, reviewed: updated)
            let confirmed = try store.records()
            guard confirmed.allSatisfy({ !$0.changes.contains(where: { $0.state == .outgoing || $0.state == .conflict }) }) else { throw NotionProjectSync.SyncError.unsupported("Update did not acknowledge all requested fields.") }
            let project = confirmed.first { $0.kind == .projects }!, projectSource = sources.first { $0.kind == .projects }!
            guard project.value("one liner", source: projectSource).display == "Updated round-trip value", !project.value("hero", source: projectSource)["relation"].array.isEmpty else { throw NotionProjectSync.SyncError.unsupported("Primary media or project edits did not round trip.") }
            let asset = confirmed.first { $0.kind == .assets }!, assetSource = sources.first { $0.kind == .assets }!
            guard let file = asset.value("preview", source: assetSource)["files"].array.first?["file"]["url"].string, let url = URL(string: file), NSImage(contentsOf: try await ProjectPreviewCache.shared.file(for: url)) != nil else { throw NotionProjectSync.SyncError.unsupported("Uploaded preview did not render.") }
            print("Validated create/update, relationships, collections, version association, resource URL, explicit date clearing, uploaded PNG, and primary media across 12 sources.")
        } catch { validationError = error }
        // Only returned IDs from this fixture database are eligible for cleanup.
        var archived = 0
        for var record in try store.records() where record.pageID != nil {
            do {
                let source = sources.first { $0.id == record.sourceID }!
                let page = try await client.completeProperties(try await client.graphRequest("pages/" + record.pageID!))
                try store.ingest(pages: [page], source: source)
                record = try store.record(id: record.id)!
                guard record.title.hasPrefix(prefix) else { throw NotionProjectSync.SyncError.unsupported("Validation cleanup refused an unexpected title.") }
                record.local = record.remote; record.baseline = record.remote; record.pendingUploads = []; record.archiveRequested = true
                try store.save(record)
                try await coordinator.push(ids: [record.id], reviewed: [record])
                archived += 1
            } catch { print("Validation cleanup pending for \(record.kind.title): \(error.localizedDescription)"); if validationError == nil { validationError = error } }
        }
        print("Validation fixtures archived: \(archived). Recovery database: \(directory.appendingPathComponent("validation.sqlite").path)")
        if let validationError { throw validationError }
    }
    private static func refresh(store: ProjectGraphStore, sources: [ProjectGraphSource], client: NotionClient) async throws {
        for record in try store.records() {
            guard let id = record.pageID, let source = sources.first(where: { $0.id == record.sourceID }) else { continue }
            let page = try await client.completeProperties(try await client.graphRequest("pages/" + id))
            try store.ingest(pages: [page], source: source)
        }
    }
}
private extension Array {
    func asyncMap<T>(_ transform: (Element) async throws -> T) async throws -> [T] {
        var result: [T] = []; for element in self { result.append(try await transform(element)) }; return result
    }
}
#endif
